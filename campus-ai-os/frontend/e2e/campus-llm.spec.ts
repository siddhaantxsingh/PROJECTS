import { expect, test, type Page } from "@playwright/test";
import path from "node:path";
import { fileURLToPath } from "node:url";

// Opt-in: runs only when the server was started with a local LLM
// (CAMPUS_LLM_PROVIDER=llamacpp), see docs/testing.md. Not part of CI.
const HERE = path.dirname(fileURLToPath(import.meta.url));
const PW = "correct horse battery";
test.skip(process.env.CAMPUS_LLM_PROVIDER !== "llamacpp", "needs CAMPUS_LLM_PROVIDER=llamacpp and a local GGUF model");
test.setTimeout(240_000);

async function register(page: Page, email: string, name: string) {
  await page.goto("/");
  await page.getByRole("button", { name: "New here? Create an account" }).click();
  await page.getByLabel("Email").fill(email);
  await page.getByLabel("Name").fill(name);
  await page.getByLabel("Password").fill(PW);
  await page.getByRole("button", { name: "Register" }).click();
  await expect(page.getByText(`${name} (student)`)).toBeVisible();
}

test("a local LLM writes the answer; citations are checked and shown", async ({ browser }) => {
  const prof = await (await browser.newContext()).newPage();
  await register(prof, "prof@uni.edu", "Prof Ada");
  const admin = await (await browser.newContext()).newPage();
  await admin.goto("/");
  await admin.getByLabel("Email").fill("admin@uni.edu");
  await admin.getByLabel("Password").fill("admin-password-123");
  await admin.getByRole("button", { name: "Sign in" }).click();
  await admin.getByRole("button", { name: "Admin" }).click();
  await admin.getByLabel("Role of prof@uni.edu").selectOption("faculty");
  await expect(admin.getByLabel("Role of prof@uni.edu")).toHaveValue("faculty");
  await prof.reload();
  await prof.getByLabel("Course code").fill("CS201");
  await prof.getByLabel("Course title").fill("Data Structures");
  await prof.getByRole("button", { name: "Create course" }).click();
  await prof.getByRole("button", { name: /CS201/ }).click();
  await prof.getByRole("tab", { name: "Documents" }).click();
  await prof.locator("input[type=file]").setInputFiles(path.join(HERE, "lecture.md"));
  await expect(prof.getByText(/Uploaded lecture.md/)).toBeVisible();

  // The instructor asks in the Ask tab (instructors are course members too).
  await prof.getByRole("tab", { name: "Ask" }).click();
  await prof.getByLabel("Question").fill("How are hash collisions resolved?");
  await prof.getByRole("button", { name: "Ask" }).click();
  const answer = prof.getByTestId("answer");
  await expect(answer).not.toBeEmpty({ timeout: 180_000 });
  await expect(prof.getByTestId("provider")).toContainText("Generated by a local model (qwen2.5-0.5B-F16)");
  await expect(answer).toContainText(/chaining/i);
  await expect(answer).toContainText(/\[\d\]/);                 // inline citation marker kept
  await expect(prof.getByText(/\[1\] CS201 Data Structures — p\. 1/)).toBeVisible();
  await expect(prof.getByText(/Grounded sentences: 100%/)).toBeVisible();  // enforcement leaves only supported sentences
  await prof.screenshot({ path: path.join(HERE, "..", "..", "docs", "screenshots", "ask-llm.png"), fullPage: true });
});
