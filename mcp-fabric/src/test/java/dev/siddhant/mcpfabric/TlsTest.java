package dev.siddhant.mcpfabric;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import dev.siddhant.mcpfabric.policy.Policy;
import java.io.FileInputStream;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.KeyStore;
import java.util.List;
import javax.net.ssl.SSLContext;
import javax.net.ssl.SSLHandshakeException;
import javax.net.ssl.TrustManagerFactory;
import org.junit.jupiter.api.Test;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.test.web.server.LocalServerPort;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;

/**
 * The gateway serving HTTPS directly (Spring `server.ssl`), with a keystore
 * generated by `keytool` for the test: a client that trusts the certificate
 * completes an MCP handshake over TLS 1.3; a client that does not is refused;
 * plain HTTP to the TLS port gets no MCP response.
 */
@SpringBootTest(webEnvironment = SpringBootTest.WebEnvironment.RANDOM_PORT)
class TlsTest {
    static Path keystore;
    static final String PASS = "test-pass-123";

    @LocalServerPort
    int port;

    @DynamicPropertySource
    static void props(DynamicPropertyRegistry r) throws Exception {
        Path dir = Files.createTempDirectory("fabric-tls");
        keystore = dir.resolve("tls.p12");
        String keytool = Path.of(System.getProperty("java.home"), "bin", "keytool").toString();
        var p = new ProcessBuilder(keytool, "-genkeypair", "-alias", "fabric", "-keyalg", "EC", "-groupname", "secp256r1", "-validity", "2",
                "-dname", "CN=localhost", "-ext", "SAN=dns:localhost,ip:127.0.0.1", "-storetype", "PKCS12",
                "-keystore", keystore.toString(), "-storepass", PASS, "-keypass", PASS).inheritIO().start();
        assertThat(p.waitFor()).isZero();
        r.add("server.ssl.enabled", () -> "true");
        r.add("server.ssl.key-store", keystore::toString);
        r.add("server.ssl.key-store-type", () -> "PKCS12");
        r.add("server.ssl.key-store-password", () -> PASS);
        r.add("server.ssl.key-alias", () -> "fabric");
        r.add("server.ssl.enabled-protocols", () -> "TLSv1.3,TLSv1.2");
        r.add("fabric.auth.mode", () -> "static");
        r.add("fabric.clients[0].id", () -> "tls");
        r.add("fabric.clients[0].key-sha256", () -> Policy.sha256Hex("tls-key"));
        r.add("fabric.audit-file", () -> dir.resolve("audit.jsonl").toString());
    }

    static final String INIT = "{\"jsonrpc\":\"2.0\",\"id\":1,\"method\":\"initialize\",\"params\":{\"protocolVersion\":\"2025-06-18\",\"capabilities\":{},\"clientInfo\":{\"name\":\"t\",\"version\":\"1\"}}}";

    HttpRequest init(String scheme) {
        return HttpRequest.newBuilder(URI.create(scheme + "://localhost:" + port + "/mcp")).header("Content-Type", "application/json")
                .header("Authorization", "Bearer tls-key").POST(HttpRequest.BodyPublishers.ofString(INIT)).build();
    }

    @Test
    void mcpOverHttpsWithATrustedCertificate() throws Exception {
        KeyStore ks = KeyStore.getInstance("PKCS12");
        try (var in = new FileInputStream(keystore.toFile())) {
            ks.load(in, PASS.toCharArray());
        }
        var tmf = TrustManagerFactory.getInstance(TrustManagerFactory.getDefaultAlgorithm());
        tmf.init(ks);
        var ctx = SSLContext.getInstance("TLS");
        ctx.init(null, tmf.getTrustManagers(), null);
        var client = HttpClient.newBuilder().sslContext(ctx).build();

        HttpResponse<String> r = client.send(init("https"), HttpResponse.BodyHandlers.ofString());
        assertThat(r.statusCode()).isEqualTo(200);
        assertThat(r.headers().firstValue("Mcp-Session-Id")).isPresent();
        assertThat(r.body()).contains("\"protocolVersion\":\"2025-06-18\"");
        assertThat(r.sslSession()).isPresent();
        assertThat(r.sslSession().get().getProtocol()).isEqualTo("TLSv1.3");
        assertThat(List.of(r.sslSession().get().getPeerCertificates())).hasSize(1);
    }

    @Test
    void untrustedCertificateAndPlainHttpAreRefused() throws Exception {
        assertThatThrownBy(() -> HttpClient.newHttpClient().send(init("https"), HttpResponse.BodyHandlers.ofString()))
                .isInstanceOf(SSLHandshakeException.class);
        int status;
        try {
            status = HttpClient.newHttpClient().send(init("http"), HttpResponse.BodyHandlers.ofString()).statusCode();
        } catch (java.io.IOException e) {
            status = -1; // connection closed: also a refusal
        }
        assertThat(status).as("plain HTTP on the TLS port").isNotEqualTo(200);
    }
}
